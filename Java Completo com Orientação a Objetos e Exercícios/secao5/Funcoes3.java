package secao5;

public class Funcoes3 {
    public static void main(String[] args) {
        String frase = "java é a melhor linguagem de todas";

        System.out.println(frase.length());

        System.out.println(frase.substring(0,4));

        System.out.println(frase.toUpperCase());

        System.out.println(frase.replaceAll("a", "e"));

        System.out.println(Math.sqrt(26));

        System.out.println(Math.pow(2, 3));

        System.out.println(Math.abs(-89));

        System.out.println(Math.max(100, 99));
    }
}
